"""Assemble the captured MyNomos result order and reviewed CyLaw briefs.

Offline and deterministic: no network requests or generated legal content.
Source block numbers are local navigation anchors, not judicial paragraph numbers.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / "outputs/real-cases-manifest.json").read_text())
records = []
for entry in manifest["cases"]:
    case_id = entry["id"]
    source = json.loads((ROOT / f"outputs/real-case-sources/{case_id}.json").read_text())
    brief = json.loads((ROOT / f"outputs/real-case-briefs/{case_id}.json").read_text())
    assert source["id"] == brief["id"] == case_id
    assert entry["rank"] == source["rank"] == brief["rank"]
    valid_blocks = {p["n"] for p in source["paragraphs"]}
    for section, refs in brief["sectionRefs"].items():
        assert refs and set(refs) <= valid_blocks, (case_id, section)
    records.append({
        **brief,
        "year": brief["date"][:4],
        "matter": manifest["query"],
        "tone": "neutral",
        "sourceUrl": source["sourceUrl"],
        "sourceName": source["sourceName"],
        "sourceRetrievedAt": source["sourceRetrievedAt"],
        "sourceHash": source["sha256"],
        "sourceTitle": source["htmlTitle"],
        "sourceNote": "CyLaw judgment text. Source block numbers are local navigation anchors, not official judicial paragraph numbers.",
        "paragraphs": source["paragraphs"],
    })

assert len(records) == 10
assert len({c["id"] for c in records}) == 10
valid_ids = {c["id"] for c in records}
assert all(set(c["related"]) <= valid_ids for c in records)
collection = {key: value for key, value in manifest.items() if key != "cases"}
collection["source"] = "CyLaw"
collection["count"] = len(records)
output = (
    "// Generated by scripts/build-real-case-data.py from reviewed, source-backed briefs.\n"
    "// Real judgments; prepared summaries. Source blocks are local navigation anchors.\n"
    f"export const CASE_COLLECTION = {json.dumps(collection, ensure_ascii=False, indent=2)};\n\n"
    f"export const CASES = {json.dumps(records, ensure_ascii=False, indent=2)};\n\n"
    "export const TOPICS = [...new Set(CASES.flatMap(item => item.tags))];\n"
)
(ROOT / "modules/case-data.js").write_text(output)
print(f"Built {len(records)} real cases, {sum(len(c['paragraphs']) for c in records)} source blocks.")
